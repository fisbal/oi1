export type WorkLang = 'fr' | 'en' | 'es' | 'pt' | 'de';
const AT = { es: 0, pt: 1, de: 2 } as const;

/** The text in the given language: French and English come from works.ts, the others from the table above. */
export function workText(fr: string, en: string, lang: WorkLang): string {
  if (lang === 'fr') return fr;
  if (lang === 'en') return en;
  const tr = WORKS_TR[en]?.[AT[lang]];
  if (tr === undefined) WORKS_MISSING.add(en);
  return tr ?? en;
}

